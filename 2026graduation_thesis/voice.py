from vosk import Model, KaldiRecognizer
import json

#=============================================================================================
#音声認識のためのモデルの読み込み
#モデルのパスは環境に応じて変更してください
#=============================================================================================
model = Model(
    "/home/hirano/Audiodevicerecognition/vosk-model/vosk-model-small-ja-0.22"
)

#============================================================================================
#音声認識のための辞書の作成、語彙の指定
#============================================================================================
vocabulary = json.dumps(
    ["前", "後ろ", "右", "左", "止まれ", "戻れ"],
    ensure_ascii=False
)

recognizer = KaldiRecognizer(
    model,
    16000,
    vocabulary
)